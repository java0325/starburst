-- [쿼리 0] 제대별 부대 수 현황 (bar chart)
SELECT "제대", "부대수", "비고"
FROM (VALUES
    ('군단', 3, '작전사 예하 군단'),
    ('사단', 12, '기계화·보병·특공 사단'),
    ('여단', 28, '독립여단·지원여단'),
    ('연대', 45, '각 기능별 연대'),
    ('대대', 187, '전투·지원 대대'),
    ('중대', 892, '전투·전투지원 중대')
) AS t("제대", "부대수", "비고")
ORDER BY "부대수" ASC;

-- [쿼리 1] 기능별 부대 분류
SELECT "기능", "부대수", "비율(%)"
FROM (VALUES
    ('전투병과', 312, 47.2),
    ('전투지원', 198, 29.9),
    ('전투근무지원', 152, 22.9)
) AS t("기능", "부대수", "비율(%)");
