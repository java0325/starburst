-- [쿼리 0] 작전 유형별 임무 개념 수 (bar chart)
SELECT "작전유형", "임무개념수", "우선순위"
FROM (VALUES
    ('전면전 방어',   85, '최우선'),
    ('국지도발 대응', 62, '최우선'),
    ('대침투·대특작', 47, '고'),
    ('사이버·전자전', 38, '고'),
    ('민사작전',      29, '중'),
    ('재해재난 지원', 24, '중'),
    ('해외파병',      18, '저'),
    ('연합훈련',      33, '중')
) AS t("작전유형", "임무개념수", "우선순위")
ORDER BY "임무개념수" DESC;

