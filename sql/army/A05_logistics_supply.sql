-- [쿼리 0] 보급품 분류별 재고 현황 (bar chart)
SELECT "분류", "품목수", "재고율(%)"
FROM (VALUES
    ('탄약류',       1840, 72.4),
    ('유류·연료',     320, 85.1),
    ('식량·급식',    2140, 91.3),
    ('피복·장구류',  3820, 88.7),
    ('의무보급품',    980, 79.2),
    ('공병자재',     1260, 68.4),
    ('통신장비부품',  740, 83.6),
    ('차량부품',     2180, 76.9),
    ('화학방호장비',  430, 94.2),
    ('일반보급품',   4560, 89.5)
) AS t("분류", "품목수", "재고율(%)")
ORDER BY "품목수" DESC;

