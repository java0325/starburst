    ('assigned-to (배속)', 98, '부대-인원 배속 관계'),
    ('uses (사용)', 112, '인원-장비 사용 관계'),
    ('located-at (위치)', 67, '부대-시설 위치 관계'),
    ('supports (지원)', 54, '부대간 지원 관계')
) AS t("관계유형", "관계수", "설명")
