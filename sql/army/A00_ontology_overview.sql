-- [쿼리 0] 온톨로지 도메인별 개념 분류 현황 (bar chart)
SELECT "도메인", "개념수", "비고"
FROM (VALUES
    ('부대편성', 42, '부대·지휘관계·편제 개념'),
    ('인원관리', 38, '군인·보직·계급·임무 개념'),
    ('장비체계', 55, '무기·차량·통신장비 개념'),
    ('작전수행', 47, '작전계획·기동·전투 개념'),
    ('군수지원', 33, '보급·정비·수송 개념'),
    ('시설관리', 28, '부대시설·훈련장·창고 개념'),
    ('교육훈련', 31, '훈련과정·평가·자격 개념'),
    ('정보체계', 25, '데이터·시스템·인터페이스 개념')
) AS t("도메인", "개념수", "비고")
ORDER BY "개념수" DESC;

-- [쿼리 1] 온톨로지 관계 유형별 현황
