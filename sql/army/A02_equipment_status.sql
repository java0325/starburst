-- [쿼리 0] 장비 유형별 보유 현황 (bar chart)
SELECT "장비유형", "보유수량", "가동률(%)"
FROM (VALUES
    ('전차',          280,  88.2),
    ('장갑차',        620,  91.4),
    ('자주포',        180,  85.7),
    ('견인포',        340,  79.3),
    ('다련장로켓',     42,  93.1),
    ('대공화기',      215,  87.6),
    ('헬기',          186,  82.4),
    ('공병장비',      430,  76.8),
    ('통신장비',     1240,  94.2),
    ('군용차량',     4520,  88.9)
) AS t("장비유형", "보유수량", "가동률(%)")
ORDER BY "보유수량" DESC;

